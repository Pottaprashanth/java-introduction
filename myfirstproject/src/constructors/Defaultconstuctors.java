package constructors;

public class Defaultconstuctors {
	int x;
	int y;

	public static void main(String[] args) {
		// we didn't created any structure
		// Default constructor invoke here
		Defaultconstuctors dc = new Defaultconstuctors();

		System.out.println("Num 1:" + dc.x);
		System.out.println("Num 2:" + dc.y);

	}

}
